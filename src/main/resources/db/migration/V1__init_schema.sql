CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CONSTRAINT chk_app_user_role CHECK (role IN ('MEMBER', 'ADJUSTER', 'ADMIN')),
    full_name     VARCHAR(200) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE policy (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number     VARCHAR(50)    NOT NULL UNIQUE,
    member_id         BIGINT         NOT NULL REFERENCES app_user (id),
    start_date        DATE           NOT NULL,
    end_date          DATE           NOT NULL,
    status            VARCHAR(20)    NOT NULL CHECK (status IN ('ACTIVE', 'LAPSED', 'CANCELLED')),
    annual_deductible NUMERIC(12, 2) NOT NULL CHECK (annual_deductible >= 0),
    deductible_met    NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (deductible_met >= 0),
    coinsurance_rate  NUMERIC(5, 4)  NOT NULL CHECK (coinsurance_rate BETWEEN 0 AND 1),
    annual_maximum    NUMERIC(12, 2) NOT NULL CHECK (annual_maximum >= 0),
    benefits_paid_ytd NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (benefits_paid_ytd >= 0),
    CHECK (end_date >= start_date)
);

CREATE TABLE covered_service (
    service_code VARCHAR(10)  PRIMARY KEY,
    description  VARCHAR(200) NOT NULL,
    covered      BOOLEAN      NOT NULL
);

CREATE TABLE claim (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number          VARCHAR(30)    NOT NULL UNIQUE,
    policy_id             BIGINT         NOT NULL REFERENCES policy (id),
    provider_name         VARCHAR(200)   NOT NULL,
    service_code          VARCHAR(10)    NOT NULL,
    service_date          DATE           NOT NULL,
    submission_date       DATE           NOT NULL,
    billed_amount         NUMERIC(12, 2) NOT NULL CONSTRAINT chk_claim_billed_amount CHECK (billed_amount > 0),
    status                VARCHAR(20)    NOT NULL
        CONSTRAINT chk_claim_status CHECK (status IN ('SUBMITTED', 'IN_REVIEW', 'APPROVED', 'DENIED', 'PAID')),
    denial_reason         VARCHAR(1000),
    deductible_applied    NUMERIC(12, 2),
    coinsurance_amount    NUMERIC(12, 2),
    plan_paid             NUMERIC(12, 2),
    member_responsibility NUMERIC(12, 2),
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_claim_policy ON claim (policy_id);
CREATE INDEX idx_claim_status ON claim (status);
-- Supports the duplicate-claim lookup
CREATE INDEX idx_claim_duplicate ON claim (policy_id, service_date, service_code);
CREATE INDEX idx_policy_member ON policy (member_id);

-- Append-only audit trail: who did what, to which record, and when.
CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor       VARCHAR(100)  NOT NULL,
    action      VARCHAR(50)   NOT NULL,
    entity_type VARCHAR(50)   NOT NULL,
    entity_id   VARCHAR(100),
    details     VARCHAR(2000),
    request_id  VARCHAR(64)
);

CREATE INDEX idx_audit_entity ON audit_event (entity_type, entity_id);
CREATE INDEX idx_audit_actor ON audit_event (actor);
CREATE INDEX idx_audit_occurred ON audit_event (occurred_at);
